/**
 * Generates tiny base64 LQIP (Low Quality Image Placeholder) data URLs for every
 * gallery photograph, written out to app/data/galleryBlur.ts.
 *
 * These feed next/image's `placeholder="blur"`. Because the gallery builds its
 * image paths dynamically (rather than via static imports), Next cannot derive
 * blurDataURL automatically — it has to be supplied.
 *
 * Each placeholder is a 12px-wide WebP, so the whole map costs a few KB rather
 * than the ~34KB *per image* the existing thumb/ files would.
 *
 * Run:  node generate-gallery-blur.js
 * Re-run whenever photographs are added to public/images/gallery/<year>/large.
 */
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const EDITIONS = ['2018', '2019'];
const LQIP_WIDTH = 12;
const OUT_FILE = path.join(__dirname, 'app', 'data', 'galleryBlur.ts');

async function generate() {
  const entries = [];

  for (const edition of EDITIONS) {
    const dir = path.join(__dirname, 'public', 'images', 'gallery', edition, 'large');
    if (!fs.existsSync(dir)) {
      console.warn(`Skipping ${edition}: ${dir} not found`);
      continue;
    }

    const files = fs
      .readdirSync(dir)
      .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
      .sort();

    for (const file of files) {
      const source = sharp(path.join(dir, file));
      const { width, height } = await source.metadata();

      const buffer = await source
        .resize({ width: LQIP_WIDTH })
        .webp({ quality: 45 })
        .toBuffer();

      // Key matches the public URL that galleryPages.ts builds.
      const key = `/images/gallery/${edition}/large/${encodeURI(file)}`;
      entries.push([
        key,
        {
          blurDataURL: `data:image/webp;base64,${buffer.toString('base64')}`,
          width,
          height,
        },
      ]);
    }

    console.log(`${edition}: ${files.length} placeholders`);
  }

  const body = entries
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join('\n');

  const contents = `// AUTO-GENERATED by generate-gallery-blur.js — do not edit by hand.
// ${entries.length} entries: ${LQIP_WIDTH}px WebP placeholder plus intrinsic
// dimensions, keyed by public image path.

export interface GalleryImageMeta {
  blurDataURL: string;
  width: number;
  height: number;
}

export const galleryBlur: Record<string, GalleryImageMeta> = {
${body}
};

/** Neutral fallback for any path missing from the map. */
export const FALLBACK_META: GalleryImageMeta = {
  blurDataURL:
    "data:image/svg+xml;base64,${Buffer.from(
      '<svg xmlns="http://www.w3.org/2000/svg" width="12" height="8"><rect width="12" height="8" fill="#e5e5e5"/></svg>',
    ).toString('base64')}",
  width: 1500,
  height: 1000,
};
`;

  fs.writeFileSync(OUT_FILE, contents, 'utf8');
  const kb = (Buffer.byteLength(contents) / 1024).toFixed(1);
  console.log(`Wrote ${entries.length} placeholders to app/data/galleryBlur.ts (${kb} KB)`);
}

generate().catch((err) => {
  console.error('Failed to generate gallery placeholders:', err);
  process.exit(1);
});
